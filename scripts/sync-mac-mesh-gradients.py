#!/usr/bin/env python3
"""Regenerate the Mac Script.js ``SELF_MESH_GRADIENTS`` table from mesh-gradients.yaml.

Why: the sub-share subscriber tier strips the ``·mesh`` clones (they are
unreachable off-mesh), so the Mac Script.js re-adds them and needs each host's
mesh IP. Hand-copying those IPs into the script duplicated the private
``airports/mesh-gradients.yaml`` and the two could drift silently (a stale IP
just makes the mesh fallback dead). This tool makes the YAML the single source
of truth: it rewrites only the block between the two markers.

    // @mesh-gradients:begin ...
    const SELF_MESH_GRADIENTS = { ... };
    // @mesh-gradients:end

Usage:
    sync-mac-mesh-gradients.py --spec mesh-gradients.yaml --script Script.js           # rewrite
    sync-mac-mesh-gradients.py --spec mesh-gradients.yaml --script Script.js --check   # exit 1 on drift
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

import yaml

BEGIN = "// @mesh-gradients:begin"
END = "// @mesh-gradients:end"
_BLOCK_RE = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)


def load_table(spec_path: Path) -> dict[str, str]:
    data = yaml.safe_load(spec_path.read_text(encoding="utf-8")) or {}
    if not isinstance(data, dict):
        raise ValueError(f"{spec_path}: top level must be a mapping")
    table: dict[str, str] = {}
    for item in data.get("hosts") or []:
        if not isinstance(item, dict):
            continue
        name = str(item.get("name") or "").strip()
        mesh = str(item.get("mesh-server") or "").strip()
        if name and mesh:
            table[name] = mesh
    if not table:
        raise ValueError(f"{spec_path}: no host with both name and mesh-server")
    return table


def render_block(table: dict[str, str]) -> str:
    rows = "\n".join(f"  {json.dumps(k, ensure_ascii=False)}: {json.dumps(v)}," for k, v in table.items())
    return (
        f"{BEGIN} (generated by scripts/sync-mac-mesh-gradients.py from "
        "airports/mesh-gradients.yaml; do not edit by hand)\n"
        f"const SELF_MESH_GRADIENTS = {{\n{rows}\n}};\n"
        f"{END}"
    )


def sync(script_text: str, table: dict[str, str]) -> str:
    matches = _BLOCK_RE.findall(script_text)
    if len(matches) != 1:
        raise ValueError(f"expected exactly one {BEGIN} ... {END} block, found {len(matches)}")
    return _BLOCK_RE.sub(lambda _m: render_block(table), script_text, count=1)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--spec", required=True, type=Path, help="airports/mesh-gradients.yaml")
    ap.add_argument("--script", required=True, type=Path, help="Mac Clash Verge profiles/Script.js")
    ap.add_argument("--check", action="store_true", help="report drift only, exit 1 if out of sync")
    args = ap.parse_args(argv)
    try:
        table = load_table(args.spec)
        current = args.script.read_text(encoding="utf-8")
        updated = sync(current, table)
    except (OSError, ValueError, yaml.YAMLError) as e:
        print(f"ERROR: {e}", file=sys.stderr)
        return 2
    if updated == current:
        print(f"IN SYNC: {len(table)} hosts")
        return 0
    if args.check:
        print(f"DRIFT: {args.script} SELF_MESH_GRADIENTS differs from {args.spec}", file=sys.stderr)
        return 1
    tmp = args.script.with_name(args.script.name + ".sync-tmp")
    tmp.write_text(updated, encoding="utf-8")
    tmp.replace(args.script)
    print(f"UPDATED: {len(table)} hosts -> {args.script}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
